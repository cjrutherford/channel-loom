import { expect, test } from '@playwright/test';

test('Studio forms explain rejected edits and guard pending saves', async ({ page }) => {
  test.skip(process.env.E2E_ISOLATED !== '1', 'Requires isolated fixture server');
  await page.goto('/admin');
  await page.locator('#username').fill('fixture');
  await page.locator('#password').fill(process.env.E2E_PASSWORD!);
  await page.locator('#submitBtn').click();
  await expect(page.locator('#healthText')).toHaveText('SYSTEM ONLINE');
  await page.locator('[data-view="settings"]').click();
  const audio = page.locator('#setAudioLanguage');
  await audio.fill('abcdefghijklmnopq');
  await page.locator('#saveLanguageBtn').focus();
  await page.keyboard.press('Enter');
  await expect(page.locator('#saveLanguageBtnStatus')).toBeFocused();
  await expect(audio).toHaveAttribute('aria-invalid', 'true');
  await expect(audio).toHaveAttribute('aria-describedby', /setAudioLanguageError/);
  await expect(audio).toHaveValue('abcdefghijklmnopq');
  await audio.fill('fra');
  await page.locator('#saveLanguageBtn').click();
  await expect(page.locator('#saveLanguageBtnStatus')).toContainText('saved');
  await expect(audio).toHaveValue('fra');
  await page.locator('[data-view="programming"]').click();
  const crf = page.locator('#streamCrf');
  await crf.fill('33');
  await page.locator('#saveStreamBtn').click();
  await expect(crf).toHaveAttribute('aria-invalid', 'true');
  await expect(crf).toHaveValue('33');
  await crf.fill('22');
  await page.locator('#saveStreamBtn').click();
  await expect(page.locator('#saveStreamBtnStatus')).toContainText('saved');
  const streamAudio = page.locator('#streamAudioLanguage');
  await streamAudio.fill('abcdefghijklmnopq');
  await page.locator('#saveStreamBtn').click();
  await expect(page.locator('#saveStreamBtnStatus')).toBeFocused();
  await expect(page.locator('#saveStreamBtnStatus')).toContainText('Check both audio and subtitle language codes');
  await expect(streamAudio).toHaveValue('abcdefghijklmnopq');
  await streamAudio.fill('eng');
  await page.locator('#saveStreamBtn').click();
  await expect(page.locator('#saveStreamBtnStatus')).toContainText('saved');
  await page.locator('[data-view="sources"]').click();
  await page.locator('#cloudName').fill('Fixture Drive');
  await page.locator('#cloudSecret').fill('fixture-secret');
  await page.locator('#addCloudSourceBtn').click();
  await expect(page.locator('#cloudSecret')).toHaveAttribute('aria-invalid', 'true');
  await expect(page.locator('#cloudSecret')).toHaveValue('fixture-secret');
  await page.locator('#cloudAuth').selectOption('access_token');
  await page.locator('#cloudRootId').fill('../invalid');
  await page.locator('#addCloudSourceBtn').click();
  await expect(page.locator('#cloudRootId')).toHaveAttribute('aria-invalid', 'true');
  await expect(page.locator('#cloudSecret')).toHaveValue('fixture-secret');
  await expect(page.locator('#addCloudSourceBtnStatus')).not.toContainText('fixture-secret');
  await page.locator('#cloudRootId').fill('root');
  let calls = 0;
  await page.route('**/api/v1/cloud/sources', async route => {
    if (route.request().method() !== 'POST') return route.continue();
    calls++;
    await new Promise(resolve => setTimeout(resolve, 500));
    await route.fulfill({ status: 503, body: 'fixture-secret' });
  });
  await page.locator('#addCloudSourceBtn').click();
  await expect(page.locator('#addCloudSourceBtn')).toBeDisabled();
  await page.locator('#addCloudSourceBtn').evaluate((el: HTMLButtonElement) => el.click());
  await expect(page.locator('#addCloudSourceBtnStatus')).toContainText('try again');
  expect(calls).toBe(1);
  await expect(page.locator('#cloudSecret')).toHaveValue('fixture-secret');
  await expect(page.locator('#addCloudSourceBtnStatus')).not.toContainText('fixture-secret');
  await page.unrouteAll();
  await page.locator('#addCloudSourceBtn').click();
  await expect(page.locator('#addCloudSourceBtnStatus')).toContainText('added');
  await expect(page.locator('#cloudSecret')).toHaveValue('');
  await page.locator('#cloudFolderId').fill('../invalid');
  await page.locator('#addCloudRootBtn').click();
  await expect(page.locator('#cloudFolderId')).toHaveAttribute('aria-invalid', 'true');
  await expect(page.locator('#addCloudRootBtnStatus')).toBeFocused();
  await page.locator('#cloudFolderId').fill('root');
  await page.locator('#addCloudRootBtn').click();
  await expect(page.locator('#addCloudRootBtnStatus')).toContainText('added');
  await page.screenshot({ path: 'test-results/wave-8-studio-forms.png' });
  await page.locator('[data-view="library"]').click();
  await expect(page.getByRole('textbox', { name: 'Search library titles' })).toBeVisible();
});
